/*
 * c55math.h - ручні реалізації арифметики для TMS320C55x.
 *
 * Мета: перевірити, чи можна обійти підпрограми компілятора (__mpyli, __mpyd,
 * __addd, __divli), які виявились аномально дорогими (fp32: ~3350 тактів на
 * множення-накопичення, int32: 1.47 MMAC/s проти 50.2 у Q15).
 *
 * Апаратна база C55x, з якої виходимо:
 *   - один множник 17x17 -> 32 біти (MPYM/MACM), тобто 16x16 "безкоштовно";
 *   - акумулятори AC0..AC3 по 40 біт;
 *   - `int` = 16 біт, `long` = 32 біти, `double` == `float` == 32 біти;
 *   - зсуви на змінну кількість - одна інструкція.
 *
 * Усе тут написане так, щоб компілятор МУСИВ згенерувати 16x16 множення:
 * операнди звужені до 16 біт (`int`/`unsigned int`) ПЕРЕД множенням, а
 * розширення до 32 біт зроблено явним приведенням кожного співмножника.
 * Саме форма `(long)(int)x * (long)(int)y` розпізнається cl55 як MPYM;
 * `(long)x * (long)y` для 32-бітних x,y дає виклик __mpyli.
 *
 * ASCII only: препроцесор cl55 4.4.1 не приймає не-ASCII байти.
 */

/* Переносимі типи. Потрібні НЕ для краси: результати з DSP прочитати нічим
 * (черга повідомлень мертва, значення з create не доходить), тож єдиний спосіб
 * перевірити ПРАВИЛЬНІСТЬ цієї арифметики - зібрати той самий вихідний код на
 * ПК і звірити з еталонною. Для цього 16-бітні половинки мусять називатись
 * окремим типом, а не `int`, який на ПК 32-бітний.
 *
 * `unsigned long` = 32 біти і на C55x, і на Windows, тож він лишається як є. */
#ifdef __TMS320C55X__
typedef unsigned int   bm_u16;
typedef int            bm_s16;
#else
typedef unsigned short bm_u16;
typedef short          bm_s16;
#endif

/* --------------------------------------------------------------------------
 * 1. MAC без звернень до пам'яті.
 *
 * Потрібне, щоб розділити дві гіпотези про 4.4 такти на MAC у Q15:
 *   (а) вузол лежить у зовнішній пам'яті без кешу -> кожен операнд коштує;
 *   (б) DSP працює значно нижче за номінальні 220 МГц.
 * Тут операнди в регістрах, звернень до пам'яті в циклі нема взагалі. Якщо
 * швидкість підскочить у рази - винна пам'ять; якщо ні - винна частота.
 *
 * `x` змінюється щоітерації, інакше -o3 згорне цикл у закритий вираз.
 * -------------------------------------------------------------------------- */
static long dsp_reg_mac(int x, int y, int n)
{
    long acc = 0;
    int i;
    for (i = 0; i < n; i++)
        {
        acc += (long)x * (long)y;
        x++;
        }
    return acc;
}

/* --------------------------------------------------------------------------
 * 2. Ручне 32x32 -> молодші 32 біти, через три 16x16.
 *
 *   a = ah:al, b = bh:bl  (al, bl - БЕЗЗНАКОВІ молодші половини)
 *   a*b mod 2^32 = al*bl + ((al*bh + ah*bl) << 16)
 *
 * Старша частина (ah*bh) впливає лише на біти >= 32, тож для молодших 32 біт
 * не потрібна. Отже три множення замість повного набору в __mpyli.
 * -------------------------------------------------------------------------- */
static long dsp_mul32(long a, long b)
{
    bm_u16 al = (bm_u16)a;
    bm_u16 bl = (bm_u16)b;
    bm_s16 ah = (bm_s16)((unsigned long)a >> 16);
    bm_s16 bh = (bm_s16)((unsigned long)b >> 16);

    unsigned long lo  = (unsigned long)al * (unsigned long)bl;
    unsigned long mid = (unsigned long)((long)ah * (long)bl)
                      + (unsigned long)((long)al * (long)bh);

    return (long)(lo + (mid << 16));
}

/* --------------------------------------------------------------------------
 * 3. IEEE-754 binary32 вручну.
 *
 * СВІДОМІ спрощення (задокументовані, бо це впливає на застосовність):
 *   - без денормалізованих чисел: вони трактуються як нуль;
 *   - без NaN/Inf: переповнення насичується до максимального скінченного;
 *   - округлення - усічення, а не "до найближчого парного".
 * Для DSP-обчислень (фільтри, згортки) це прийнятно; для загальної математики
 * - ні. Саме тому воно тут окремою функцією, а не підміною __mpyd.
 *
 * Формат: [31] знак, [30:23] порядок зі зсувом 127, [22:0] мантиса.
 * -------------------------------------------------------------------------- */

#define F32_EXP(x)   ((int)(((unsigned long)(x) >> 23) & 0xFFu))
#define F32_SIGN(x)  ((unsigned long)(x) & 0x80000000uL)
#define F32_MANT(x)  (((unsigned long)(x) & 0x7FFFFFuL) | 0x800000uL)

static long dsp_fmul(long a, long b)
{
    int ea = F32_EXP(a);
    int eb = F32_EXP(b);
    unsigned long sign = F32_SIGN(a) ^ F32_SIGN(b);
    unsigned long ma, mb, p;
    bm_u16 ml, mh, nl, nh;
    int e;

    if (ea == 0 || eb == 0)
        return 0;                        /* нуль або денормал -> нуль */

    ma = F32_MANT(a);
    mb = F32_MANT(b);

    /* 24x24 -> потрібні лише старші біти добутку. Розкладаємо на 16x16:
     * ma = mh:ml, mb = nh:nl (mh, nh - по 8 значущих біт, бо мантиса 24-бітна).
     * p = mh*nh << 16 + (mh*nl + ml*nh) + (ml*nl >> 16)
     * Молодший доданок дає лише біти округлення, але без нього втрачається
     * точність саме там, де мантиси майже рівні, тому лишаємо. */
    ml = (bm_u16)ma;
    mh = (bm_u16)(ma >> 16);
    nl = (bm_u16)mb;
    nh = (bm_u16)(mb >> 16);

    p = (unsigned long)((long)mh * (long)nh) << 16;
    p += (unsigned long)((long)mh * (long)nl);
    p += (unsigned long)((long)ml * (long)nh);
    p += ((unsigned long)((long)ml * (long)nl)) >> 16;

    /* Добуток двох 1.23-мантис лежить у [1,4), тобто в p біт 31 або 30 -
     * старший. Нормалізуємо до 24 біт. */
    e = ea + eb - 127;
    if (p & 0x80000000uL)
        { p >>= 8; e += 1; }
    else
        { p >>= 7; }

    if (e <= 0)
        return (long)sign;               /* антипереповнення -> нуль */
    if (e >= 255)
        return (long)(sign | 0x7F7FFFFFuL);   /* насичення, не Inf */

    return (long)(sign | ((unsigned long)e << 23) | (p & 0x7FFFFFuL));
}

static long dsp_fadd(long a, long b)
{
    int ea = F32_EXP(a);
    int eb = F32_EXP(b);
    unsigned long ma, mb;
    unsigned long sa = F32_SIGN(a), sb = F32_SIGN(b);
    unsigned long r;
    int e, d;

    if (ea == 0) return b;
    if (eb == 0) return a;

    /* Більший порядок - у 'a'. Обмін робить решту коду однозначною. */
    if (eb > ea)
        {
        long t = a; a = b; b = t;
        d = ea; ea = eb; eb = d;
        r = sa; sa = sb; sb = r;
        }

    d = ea - eb;
    if (d > 24)
        return a;                        /* другий доданок нижче точності */

    /* Зсув на 3 біти вгору - запас під перенос і округлення. */
    ma = F32_MANT(a) << 3;
    mb = F32_MANT(b) << 3;
    mb >>= d;

    e = ea;
    if (sa == sb)
        {
        r = ma + mb;
        if (r & 0x8000000uL)             /* переніс за 27-й біт */
            { r >>= 1; e += 1; }
        }
    else
        {
        if (ma >= mb)
            r = ma - mb;
        else
            { r = mb - ma; sa = sb; }
        if (r == 0)
            return 0;
        /* Нормалізація вліво. Цикл, бо величина зсуву залежить від даних;
         * на C55x це прямо лягає на EXP/NORM, але тримаємо переносимо. */
        while ((r & 0x4000000uL) == 0)
            {
            r <<= 1;
            e -= 1;
            if (e <= 0)
                return (long)sa;
            }
        }

    r >>= 3;
    if (e >= 255)
        return (long)(sa | 0x7F7FFFFFuL);
    if (e <= 0)
        return (long)sa;

    return (long)(sa | ((unsigned long)e << 23) | (r & 0x7FFFFFuL));
}

/* --------------------------------------------------------------------------
 * 4. Ділення 32/32 зсувом-відніманням, беззнакове.
 *
 * 32 ітерації по кілька інструкцій. C55x має інструкцію умовного віднімання
 * SUBC саме для цього, і cl55 подекуди її вставляє - перевіряємо, чи вийде
 * швидше за __divul з базового образу.
 * -------------------------------------------------------------------------- */
static unsigned long dsp_divu32(unsigned long num, unsigned long den)
{
    unsigned long q = 0;
    unsigned long r = 0;
    int i;

    if (den == 0)
        return 0xFFFFFFFFuL;

    for (i = 0; i < 32; i++)
        {
        r = (r << 1) | ((num >> 31) & 1uL);
        num <<= 1;
        q <<= 1;
        if (r >= den)
            {
            r -= den;
            q |= 1uL;
            }
        }
    return q;
}
