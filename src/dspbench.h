// Спільні параметри бенчмарку C55x vs ARM1136.
//
// ЄДИНЕ джерело правди для розмірів і вхідних даних: і ARM-реалізація (тут, у
// dsptest.cpp), і майбутній C55x-блоб мусять гнати ІДЕНТИЧНЕ навантаження на
// ІДЕНТИЧНИХ даних, інакше порівняння нічого не варте. Дані генеруються
// детерміновано (LCG) з фіксованого сіду, тож обидва боки отримують той самий
// вектор без передачі таблиць.
//
// Формат — Q15 fixed-point (16-біт знаковий, 1.15): C55x не має апаратної
// плаваючої коми (findings §6), тож чесний бенчмарк — саме fixed-point, там де
// DSP створений сяяти (dual-MAC), плюс нейтральний цілочисловий контроль.
//
// Літерали ASCII: ланцюг GCCE 3.4.3 і кирилиця в рядках коду не варті ризику.

#ifndef DSPBENCH_H
#define DSPBENCH_H

// --- розміри ядер (однакові на ARM і DSP) -----------------------------------

// Q15 dot-product: показовий для dual-MAC C55x (два множення-накопичення/такт).
// УВАГА: два буфери по 8192×2 Б = 32 КБ разом, що ВДВІЧІ більше за 16-КБ L1D
// ARM1136. Тобто це ядро впирається в пам'ять, а не в ALU — виміряно: між
// двома завантаженнями апарата воно змінилось у півтора раза при незмінній
// частоті ядра, тоді як FIR (який лишається в кеші) не змінився зовсім.
#define BENCH_DOT_N        8192

// Той самий dot-product, але робочий набір НАВМИСНО вміщується в L1D:
// два буфери по 1024×2 Б = 4 КБ разом. Це компенсує ваду попереднього ядра —
// тут міряється власне множення-накопичення, а не шина пам'яті. Саме це
// число чесно порівнювати з dual-MAC C55x; DOT на 8192 показує, що буде,
// коли дані не вміщуються.
#define BENCH_DOTS_N       1024

// Q15 FIR: класичне DSP-ядро. NTAPS множень-накопичень на вихідний відлік.
#define BENCH_FIR_TAPS     32
#define BENCH_FIR_SAMPLES  4096

// 16-бітна блочна згортка/сума — нейтральне цілочислове навантаження, щоб
// бачити межу ПОЗА сильним боком DSP.
#define BENCH_BLK_N        8192

// Скільки разів прокрутити кожне ядро в одному замірі (щоб час >> роздільної
// здатності FastCounter). Підбирається так, щоб найшвидше ядро тривало
// щонайменше кілька мілісекунд.
#define BENCH_DOT_REPS     2000
#define BENCH_DOTS_REPS    16000     // менший набір -> більше повторів
#define BENCH_FIR_REPS     200
#define BENCH_BLK_REPS     2000

// --- дзеркала навантажень create-каналу -------------------------------------
//
// Ці три навантаження існують ПАРАМИ: тут (ARM) і в src/dsp/bench_node.c (C55x),
// з однаковим вихідним кодом і однаковими даними. Довжина 1024 збігається з
// BENCH_CREATE_N на боці DSP - інакше числа непорівнянні.
//
// На C55x `double` == `float` == 32 біти, тож дзеркало навмисно рахує у `float`,
// а не в `double`: інакше ARM робив би вдвічі ширшу роботу.
#define BENCH_CREATE_N     1024

// Підібрано так, щоб на ARM кожна точка тривала десятки мілісекунд - значно
// більше за роздільну здатність FastCounter, але без ризику зачепити
// сторожовий таймер.
#define BENCH_INT32_REPS   4000
#define BENCH_FP32_REPS    2000
#define BENCH_BRANCH_REPS  4000
#define BENCH_DIV_REPS     1000

// --- детермінований генератор вхідних даних ---------------------------------
//
// Той самий LCG, що в ocprobe (Numerical Recipes). Береться молодша половина
// стану як Q15-відлік. І ARM, і DSP заповнюють свої буфери ЦИМ кодом — байт-у-
// байт однаково.

#define BENCH_LCG_SEED     0x12345678u

// Наступний стан LCG.
#define BENCH_LCG_NEXT(x)  ((x) * 1664525u + 1013904223u)

// Заповнити масив int16 значеннями Q15 з LCG. `static` (не `inline`) — щоб і
// GCCE (ARM), і cl55 (C55x, C89) взяли те саме визначення без окремого .c.
// ВАЖЛИВО: на C55x `int` 16-бітний, тож стан LCG тут строго `unsigned int`
// (32-біт на ARM) — на DSP-боці параметр приходить як 32-бітний з shared-mem,
// а сам генератор при потребі дублюється у 32-бітних типах DSP.
static void BenchFillQ15(short* dst, int n, unsigned int seed)
    {
    unsigned int x = seed;
    int i;
    for (i = 0; i < n; ++i)
        {
        x = BENCH_LCG_NEXT(x);
        // молодші 16 біт як знаковий Q15; діапазон [-1,1) у форматі 1.15
        dst[i] = (short)(x >> 16);
        }
    }

// Контрольна сума результату (щоб довести, що обидва боки порахували те саме, і
// щоб компілятор не викинув обчислення як мертве).
#define BENCH_CHECK_SEED   0u

#endif // DSPBENCH_H
