"""Integer MDEC fixture oracle. No hardware access or emulator modifications.

The two separable AAN passes use exact floor shifts. IDCT arithmetic is checked
against signed32 overflow; color arithmetic deliberately wraps modulo 2**32.
Fixtures exercise the kernel boundary, not all legal PS1 bitstreams.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def s32(value):
    assert -(1 << 31) <= value < (1 << 31), "IDCT fixture overflow"
    return value


def butterfly(p):
    def mul(a, b):
        return s32(a*b) >> 12
    z10, z11 = s32(p[0]+p[4]), s32(p[0]-p[4])
    z13 = s32(p[2]+p[6])
    z12 = s32(mul(s32(p[2]-p[6]),5793)-z13)
    a, d = s32(z10+z13), s32(z10-z13)
    b, c = s32(z11+z12), s32(z11-z12)
    z13, z10 = s32(p[3]+p[5]), s32(p[3]-p[5])
    z11, z12 = s32(p[1]+p[7]), s32(p[1]-p[7])
    h = s32(z11+z13)
    z5 = s32(s32(z12-z10)*7568)
    g = s32((s32(s32(z10*10703)+z5) >> 12)-h)
    f = s32(mul(s32(z11-z13),5793)-g)
    e = s32((s32(s32(z12*4433)-z5) >> 12)+f)
    return [s32(a+h),s32(b+g),s32(c+f),s32(d-e),
            s32(d+e),s32(c-f),s32(b-g),s32(a-h)]


def idct(block, used):
    if used == 65535:
        return [block[0]]*64
    block = block[:]
    for column in range(8):
        positions = [row*8+column for row in range(8)]
        if not used & (1 << column):
            if block[column]:
                used |= 1 << column
                for at in positions:
                    block[at] = block[column]
        else:
            values = butterfly([block[at] for at in positions])
            for at, value in zip(positions,values):
                block[at] = value
    if used == 1:
        return [block[row*8] for row in range(8) for _ in range(8)]
    return [value for row in range(8) for value in butterfly(block[row*8:row*8+8])]


def rgb24(blocks, bw):
    def clamp(x):
        return min(255,max(0,x))
    raw = []
    for y in range(16):
        for x in range(16):
            luminance = blocks[2+(y//8)*2+x//8][(y%8)*8+x%8]
            if bw:
                pixel = [clamp(luminance+128)]*3
            else:
                cr, cb = [blocks[i][(y//2)*8+x//2] for i in range(2)]
                chroma = (1434*cr,-351*cb-728*cr,1807*cb)
                pixel = []
                for term in chroma:
                    value = ((luminance << 10)+term+(1 << 19)) & 0xffffffff
                    if value & 0x80000000:
                        value -= 1 << 32
                    pixel.append(clamp((value >> 20)+128))
            raw.extend(pixel)
    return [int.from_bytes(bytes(raw[i:i+4]),"little") for i in range(0,768,4)]


def fixtures():
    results = []
    state = 0x13579bdf
    for case in range(8):
        blocks = [[0]*64 for _ in range(6)]
        for b, block in enumerate(blocks):
            if case == 1:
                block[0] = (b-3)*73
            elif case == 2:
                for row in range(8):
                    block[row*8] = (row-4)*(b+1)*3
            elif case == 3:
                for col in range(8):
                    block[col] = (col-4)*(b+1)*3
            elif case in (4,6,7):
                for at in range(64):
                    state = (state*1664525+1013904223) & 0xffffffff
                    block[at] = ((state >> 16) % 257)-128
            elif case == 5:
                block[0] = (-131072,65536,-256,-129,127,65536)[b]
        masks = []
        for block in blocks:
            mask = sum(1 << col for col in range(8) if any(block[row*8+col] for row in range(1,8)))
            # DC-only sentinel is only valid when all other63 coefficients are0.
            masks.append(65535 if not any(block[1:]) else mask)
        after = [idct(block,used) for block,used in zip(blocks,masks)]
        bw = int(case in (5,7))
        results.append(dict(case=case,bw=bw,coefficients=sum(blocks,[]),
                            used_columns=masks,idct=sum(after,[]),rgb24=rgb24(after,bw)))
    return results


def render():
    rows = fixtures()
    lines = ["// Generated by tools/mdec_reference.py; bounded integer fixtures.",
             "#ifndef MDEC_FIXTURES_H", "#define MDEC_FIXTURES_H", '#include "kernel.h"']
    for name,ctype,size in (("coefficients","mdec_s32",384),("used_columns","unsigned short",6),
                            ("idct","mdec_s32",384),("rgb24","mdec_u32",192)):
        lines.append("static const %s mdec_%s[8][%d]={" % (ctype,name,size))
        for row in rows:
            lines.append("{")
            values = row[name]
            for offset in range(0,len(values),12):
                lines.append(",".join(("0x%08xUL"%v if name=="rgb24" else str(v)+"L" if ctype=="mdec_s32" else str(v)) for v in values[offset:offset+12])+",")
            lines.append("},")
        lines.append("};")
    lines += ["static const unsigned short mdec_bw[8]={"+",".join(str(r["bw"]) for r in rows)+"};", "#endif", ""]
    data = "\n".join(lines).encode("ascii")
    target = ROOT / "src/mdec/fixtures.h"
    if target.exists():
        assert target.read_bytes()==data,"fixture drift"
    else:
        target.write_bytes(data)
    print(json.dumps(dict(cases=8,coefficients_per_case=384,rgb24_words_per_case=192,
                         sha256=hashlib.sha256(data).hexdigest().upper(),
                         masks=[r["used_columns"] for r in rows]),indent=2))


if __name__ == "__main__":
    render()
